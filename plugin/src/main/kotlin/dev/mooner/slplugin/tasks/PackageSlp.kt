package dev.mooner.slplugin.tasks

import com.android.build.api.variant.BuiltArtifactsLoader
import com.android.build.api.variant.FilterConfiguration
import dev.mooner.slplugin.apk.PluginApk
import dev.mooner.slplugin.apk.PluginApkChecker
import dev.mooner.slplugin.manifest.ManifestIssue
import org.gradle.api.DefaultTask
import org.gradle.api.GradleException
import org.gradle.api.file.DirectoryProperty
import org.gradle.api.file.RegularFileProperty
import org.gradle.api.provider.Property
import org.gradle.api.tasks.CacheableTask
import org.gradle.api.tasks.Input
import org.gradle.api.tasks.InputDirectory
import org.gradle.api.tasks.InputFile
import org.gradle.api.tasks.Internal
import org.gradle.api.tasks.Optional
import org.gradle.api.tasks.OutputDirectory
import org.gradle.api.tasks.PathSensitive
import org.gradle.api.tasks.PathSensitivity
import org.gradle.api.tasks.TaskAction
import java.io.File

/**
 * Validates the variant's APK(s) the way StarLight loads them and copies them to
 * `build/outputs/starlight/<variant>/<id>-<variant>[-<abi>].slp`.
 */
@CacheableTask
abstract class PackageSlp : DefaultTask() {

    @get:InputDirectory
    @get:PathSensitive(PathSensitivity.NAME_ONLY)
    abstract val apkDirectory: DirectoryProperty

    @get:Internal
    abstract val builtArtifactsLoader: Property<BuiltArtifactsLoader>

    @get:Input
    abstract val variantName: Property<String>

    /** The manifest generated by [GenerateStarlightManifest], when the plugin generates it. */
    @get:InputFile @get:Optional
    @get:PathSensitive(PathSensitivity.NONE)
    abstract val generatedManifest: RegularFileProperty

    @get:OutputDirectory
    abstract val outputDirectory: DirectoryProperty

    @TaskAction
    fun packageSlp() {
        val artifacts = builtArtifactsLoader.get().load(apkDirectory.get())
            ?.takeIf { it.elements.isNotEmpty() }
            ?: throw GradleException("No APK found in ${apkDirectory.get().asFile}.")
        val expectedManifest = generatedManifest.orNull?.asFile?.readText(Charsets.UTF_8)

        val issues = linkedSetOf<ManifestIssue>()
        val packaged = artifacts.elements.map { element ->
            val apk = PluginApk.read(File(element.outputFile))
            val report = PluginApkChecker.check(apk, expectedManifest)
            issues += report.issues
            Triple(apk, report.manifest, element.filters.firstOrNull { it.filterType == FilterConfiguration.FilterType.ABI }?.identifier)
        }
        ManifestReporting.reportOrThrow(logger, "the ${variantName.get()} APK", issues)

        val output = outputDirectory.get().asFile
        output.deleteRecursively()
        output.mkdirs()
        val manifest = packaged.first().second!!
        val id = manifest["id"] as String
        val outputs = packaged.map { (apk, _, abi) ->
            val name = listOfNotNull(id, variantName.get(), abi).joinToString("-") + ".slp"
            apk.file.copyTo(File(output, name), overwrite = true)
            SlpOutputs.Output(name, abi)
        }
        SlpOutputs(id, manifest["version"] as String, variantName.get(), outputs).writeTo(output)

        outputs.forEach { logger.lifecycle("StarLight plugin $id v${manifest["version"]}: ${File(output, it.file)}") }
    }
}
